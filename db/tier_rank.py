# -*- coding: utf-8 -*-
"""
CPU / 그래픽카드 성능 등급(tier_rank) 분류.

주의: 이건 스펙 텍스트에서 자동으로 뽑을 수 있는 값이 아니라, 실제 벤치마크/시장
포지셔닝 지식을 바탕으로 사람이 정한 "상품명 키워드 -> 등급" 매핑이다.
(예전 프로젝트의 tier_keyword_tables와 같은 역할, 여기서는 파이썬 딕셔너리로 관리)

등급 체계: 1(보급형) ~ 5(하이엔드) 의 5단계.
새 모델이 나오면 이 매핑에 계속 추가해줘야 한다 — 자동으로 늘어나지 않는다.
"""

import re

# ------------------------------------------------------------
# CPU 등급표
# 키: 상품명에서 찾을 정규식 패턴 (라인업 + 숫자 등급대)
# 값: tier (1~5)
# 정확한 세대별 성능 역전(예: 구형 i9 vs 신형 i5)은 반영 못 함 — "라인업상 포지션" 기준의 근사치.
# ------------------------------------------------------------
CPU_TIER_RULES = [
    # (정규식, tier)
    (r"셀러론|펜티엄", 1),
    (r"코어i3-\d+세대", 2),
    (r"코어i5-\d+세대", 3),
    (r"코어i7-\d+세대", 4),
    (r"코어i9-\d+세대|코어X-시리즈", 5),
    (r"코어 울트라5", 3),
    (r"코어 울트라7", 4),
    (r"코어 울트라9", 5),
    (r"제온", 5),  # 서버용이지만 혹시 개인 워크스테이션 용도로 남아있을 경우 대비 (보통은 exclude_rules에서 걸러짐)
]

# ------------------------------------------------------------
# 그래픽카드 등급표
# ------------------------------------------------------------
GPU_TIER_RULES = [
    (r"G210|GT ?\d{3}(?!\d)", 1),          # G210, GT710, GT730 등 로우엔드
    (r"GT ?10\d0(?!\d)", 1),                # GT1030
    (r"GTX ?10[5-6]0", 1),                  # GTX1050, 1050Ti, 1060
    (r"GTX ?16[5-6]0", 2),                  # GTX1650, 1660
    (r"RTX ?20\d0", 2),                     # RTX20xx
    # Ti 등 상위 변형은 베이스 모델보다 먼저 검사해야 한다 (안 그러면 "RTX 5060 Ti"가
    # "RTX 5060" 패턴에 먼저 걸려서 낮은 등급으로 잘못 분류된다).
    (r"RTX ?30(6|7)0 ?Ti|RTX ?307\d", 3),   # RTX3060Ti, 3070
    (r"RTX ?30[5-6]0", 2),                  # RTX3050, 3060
    (r"RTX ?308\d|RTX ?309\d", 4),          # RTX3080, 3090
    (r"RTX ?406\d ?Ti", 3),
    (r"RTX ?40[5-6]0", 2),                  # RTX4050, 4060
    (r"RTX ?407\d|RTX ?408\d", 4),          # RTX4070, 4080
    (r"RTX ?409\d", 5),                     # RTX4090
    (r"RTX ?506\d ?Ti", 3),
    (r"RTX ?505\d|RTX ?506\d", 2),          # RTX5050, 5060
    (r"RTX ?507\d", 4),                     # RTX5070
    (r"RTX ?508\d", 5),                     # RTX5080
    (r"RTX ?509\d", 5),                     # RTX5090
]


def _classify(name: str, rules: list) -> int | None:
    for pattern, tier in rules:
        if re.search(pattern, name):
            return tier
    return None


def cpu_tier(name: str) -> int | None:
    return _classify(name, CPU_TIER_RULES)


def gpu_tier(name: str) -> int | None:
    return _classify(name, GPU_TIER_RULES)


if __name__ == "__main__":
    # 간단 자가검증: 흔한 이름 몇 개로 등급이 상식과 맞는지 확인
    tests_cpu = [
        "인텔 셀러론 G5905 (코멧레이크S) (벌크)",
        "인텔 코어i5-14세대 14400F (랩터레이크 리프레시) (벌크)",
        "인텔 코어 울트라9 시리즈2 285K (애로우레이크) (정품)",
    ]
    for t in tests_cpu:
        print(t, "->", cpu_tier(t))

    tests_gpu = [
        "MSI 지포스 GT710 D3 2GB LP 무소음",
        "PALIT 지포스 RTX 5060 Ti DUAL D7 8GB 이엠텍",
        "MSI 지포스 RTX 5070 게이밍 트리오 OC D7 12GB 트라이프로져4",
    ]
    for t in tests_gpu:
        print(t, "->", gpu_tier(t))
